#!/usr/bin/env bash
# Rebuilds the chrome's typeface (D79): Recursive, subset for the writer viewer and the public
# reader shell, and the generated module both apps serve it from.
#
#   python3 -m venv /tmp/lb-venv && /tmp/lb-venv/bin/pip install fonttools brotli
#   PYTHON=/tmp/lb-venv/bin/python3 bash scripts/subset-recursive.sh
#
# Upstream: Recursive v1.085 (Google Fonts v44, https://github.com/arrowtype/recursive), as
# packaged by @fontsource-variable/recursive@5.3.0 on npm: its files/recursive-latin-full-normal.woff2,
# pinned below by SHA-256. SIL Open Font License 1.1, no Reserved Font Name
# (packages/ui/fonts/OFL.txt, from the package's LICENSE).
#
# What it keeps: the wght axis (300-1000) and the MONO axis (0-1: --mono is the same file with
# `font-variation-settings: "MONO" 1`). CASL, CRSV and slnt are pinned to the defaults (linear,
# upright). Glyphs: Basic Latin, Latin-1, the Latin-Extended letters of Windows-1252, and the
# punctuation and symbols the UI uses (dashes, quotes, ellipsis, bullet, minus, the keycap
# symbols; whatever the source lacks falls back per glyph to the system font). Layout features:
# kerning, marks, ligatures, rvrn (the font's own weight-dependent glyphs) and tabular figures.
# The hinting stays: without it, text set at a fractional size changes width with its weight.
#
# Writes packages/ui/fonts/recursive-ui.woff2 and packages/ui/src/font-data.ts (the bytes as
# base64 and their SHA-256), which packages/ui/tests/font.test.ts checks against each other.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
python="${PYTHON:-python3}"
version="5.3.0"
source_sha256="14ef41458aeba3d812284c4e32ee956910b88845062c61e91cc8578c2b78bccb"
url="https://registry.npmjs.org/@fontsource-variable/recursive/-/recursive-${version}.tgz"
unicodes="U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+0160-0161,U+0178,U+017D-017E,U+0192,U+02C6,U+02DA,U+02DC,U+2009,U+2010-2014,U+2018-201A,U+201C-201E,U+2022,U+2026,U+2030,U+2039-203A,U+2044,U+20AC,U+2122,U+2190-2193,U+21B5,U+21E7,U+2212,U+2264-2265,U+22EF,U+2318,U+2325"
features="ccmp,locl,liga,rvrn,kern,mark,mkmk,tnum,pnum"
# fontTools stamps the file's creation time with this, so a rerun writes the same bytes.
export SOURCE_DATE_EPOCH=1704067200

"$python" -c "import fontTools, brotli" 2>/dev/null || {
  echo "needs fontTools and brotli: see the header of $0" >&2
  exit 1
}

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL "$url" -o "$work/package.tgz"
tar -xzf "$work/package.tgz" -C "$work" package/files/recursive-latin-full-normal.woff2
src="$work/package/files/recursive-latin-full-normal.woff2"
echo "$source_sha256  $src" | sha256sum -c --quiet

"$python" -m fontTools.varLib.instancer "$src" wght=300:1000 MONO=0:1 CASL=0 CRSV=0.5 slnt=0 \
  -o "$work/instance.ttf" -q
out="$root/packages/ui/fonts/recursive-ui.woff2"
"$python" -m fontTools.subset "$work/instance.ttf" --unicodes="$unicodes" \
  --layout-features="$features" --flavor=woff2 --output-file="$out"

"$python" - "$out" "$root/packages/ui/src/font-data.ts" <<'PY'
import base64, hashlib, sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write(
        "// Generated by scripts/subset-recursive.sh from packages/ui/fonts/recursive-ui.woff2. Do not edit.\n"
        f'export const RECURSIVE_SHA256 = "{hashlib.sha256(data).hexdigest()}";\n'
        f'export const RECURSIVE_WOFF2_BASE64 =\n  "{base64.b64encode(data).decode()}";\n'
    )
PY
echo "wrote $(wc -c <"$out") bytes to ${out#"$root"/}"
